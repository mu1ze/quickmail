#!/usr/bin/env node
/**
 * Bundle D1 migration SQL into a TypeScript module so the Worker can apply
 * pending schema on first request. Wrangler cannot import `?raw` SQL files.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const migrationsDir = path.join(root, 'migrations');
const outFile = path.join(root, 'src/lib/server/embedded-migrations.ts');

const files = (await readdir(migrationsDir))
	.filter((name) => /^\d+_.*\.sql$/.test(name))
	.sort();

if (files.length === 0) {
	throw new Error(`No migration SQL files found in ${migrationsDir}`);
}

const migrations = [];
for (const name of files) {
	const sql = await readFile(path.join(migrationsDir, name), 'utf8');
	migrations.push({ name, sql });
}

const body = `// Generated by scripts/embed-migrations.mjs — do not edit by hand.
export type EmbeddedMigration = {
	name: string;
	sql: string;
};

export const EMBEDDED_MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(migrations, null, '\t')};
`;

await writeFile(outFile, `${body}\n`);
console.log(`Wrote ${files.length} migrations to ${path.relative(root, outFile)}`);
